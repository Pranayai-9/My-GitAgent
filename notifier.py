import os
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText

def send_review_email(
    issue_title: str,
    issue_url: str,
    repo_full_name: str,
    fork_branch_url: str,
    diff_summary: str,
    compare_pr_url: str
):
    smtp_host = os.environ.get("SMTP_HOST")
    smtp_port = int(os.environ.get("SMTP_PORT", "587"))
    smtp_user = os.environ.get("SMTP_USER")
    smtp_pass = os.environ.get("SMTP_PASS")
    recipient = os.environ.get("NOTIFICATION_EMAIL_TO")

    if not all([smtp_host, smtp_user, smtp_pass, recipient]):
        print("[Notifier] Missing SMTP configuration. Skipping email notification.")
        print(f"[Notifier] Generated Fix URL: {compare_pr_url}")
        return

    subject = f"🎯 [Review Required] Proposed Fix for {repo_full_name} (#{issue_title[:40]}...)"

    html_content = f"""
    <html>
      <body style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; line-height: 1.6; color: #24292f; max-width: 680px; margin: auto; padding: 20px;">
        <h2 style="color: #0969da; border-bottom: 1px solid #d0d7de; padding-bottom: 8px;">
          🛠️ Open Source Contribution Review Ready
        </h2>
        <p>Your OSS Agent drafted a fix for an issue. Review the diff before opening a public Pull Request.</p>

        <table style="width: 100%; border-collapse: collapse; margin-bottom: 20px;">
          <tr>
            <td style="padding: 8px; font-weight: bold; width: 140px;">Repository:</td>
            <td style="padding: 8px;"><a href="https://github.com/{repo_full_name}" target="_blank">{repo_full_name}</a></td>
          </tr>
          <tr>
            <td style="padding: 8px; font-weight: bold;">Issue:</td>
            <td style="padding: 8px;"><a href="{issue_url}" target="_blank">{issue_title}</a></td>
          </tr>
          <tr>
            <td style="padding: 8px; font-weight: bold;">Fork Branch:</td>
            <td style="padding: 8px;"><a href="{fork_branch_url}" target="_blank">{fork_branch_url}</a></td>
          </tr>
        </table>

        <div style="text-align: center; margin: 30px 0;">
          <a href="{compare_pr_url}" 
             style="background-color: #2da44e; color: #ffffff; padding: 12px 24px; text-decoration: none; border-radius: 6px; font-weight: 600; display: inline-block;">
             🔍 Review Diff & Create PR on GitHub
          </a>
        </div>

        <h3 style="color: #24292f; border-bottom: 1px solid #d0d7de; padding-bottom: 6px;">Draft Fix Summary / Diff</h3>
        <pre style="background: #f6f8fa; padding: 14px; border-radius: 6px; font-family: monospace; font-size: 13px; overflow-x: auto; white-space: pre-wrap;">{diff_summary}</pre>

        <hr style="border: none; border-top: 1px solid #d0d7de; margin: 25px 0;" />
        <p style="font-size: 12px; color: #57606a;">
          This patch was auto-generated by Gemini API and pushed to your personal fork. It will NOT be submitted to the upstream repository until you click the button above.
        </p>
      </body>
    </html>
    """

    msg = MIMEMultipart("alternative")
    msg["Subject"] = subject
    msg["From"] = smtp_user
    msg["To"] = recipient

    plain_text = f"""
Review Proposed Fix for {repo_full_name}
Issue: {issue_url}
Fork Branch: {fork_branch_url}
Create PR: {compare_pr_url}

Diff Summary:
{diff_summary}
    """

    msg.attach(MIMEText(plain_text, "plain"))
    msg.attach(MIMEText(html_content, "html"))

    try:
        with smtplib.SMTP(smtp_host, smtp_port) as server:
            server.starttls()
            server.login(smtp_user, smtp_pass)
            server.sendmail(smtp_user, recipient, msg.as_string())
        print(f"[Notifier] Notification email sent successfully to {recipient}.")
    except Exception as e:
        print(f"[Notifier] Failed to send email: {e}")
