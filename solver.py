import os
import json
import glob
from google import genai
from google.genai import types

def plan_and_patch(repo_path: str, issue_title: str, issue_body: str) -> dict:
    """
    Uses Gemini API to inspect candidate files in the cloned repository and produce patches.
    """
    api_key = os.environ.get("GEMINI_API_KEY")
    if not api_key:
        raise ValueError("GEMINI_API_KEY environment variable is not set.")

    client = genai.Client(api_key=api_key)

    # 1. Gather a map of file names to help Gemini identify the right files
    code_files = []
    for ext in ("*.py", "*.md", "*.rst", "*.json", "*.yaml", "*.yml"):
        for path in glob.glob(os.path.join(repo_path, "**", ext), recursive=True):
            rel = os.path.relpath(path, repo_path)
            if not rel.startswith((".git", ".tox", "venv", ".venv", "__pycache__")):
                code_files.append(rel)

    file_list_summary = "\n".join(code_files[:150])

    prompt = f"""
You are an expert Python open-source maintainer and engineer.
You are fixing an issue in a repository.

Issue Title: {issue_title}
Issue Description:
{issue_body}

List of files in the project:
{file_list_summary}

Task:
1. Identify the most likely file(s) that need changes to address this issue.
2. Provide the exact file path and the complete updated code or patch.
3. Be concise and precise. Avoid unnecessary refactoring. Adhere strictly to the project's style.

Respond strictly in JSON format matching this schema:
{{
  "explanation": "Brief explanation of the bug and fix",
  "files": [
    {{
      "path": "relative/path/to/file.py",
      "action": "modify" or "create",
      "content": "Full new content of the file"
    }}
  ]
}}
"""

    print("[Solver] Requesting patch plan from Gemini API...")
    # First turn: ask Gemini to pick candidate files or generate patch
    response = client.models.generate_content(
        model="gemini-2.0-flash",
        contents=prompt,
        config=types.GenerateContentConfig(
            response_mime_type="application/json"
        )
    )

    try:
        result = json.loads(response.text)
        return result
    except Exception as e:
        print(f"[Solver] Failed to parse JSON response: {e}\nRaw output: {response.text}")
        return {"explanation": "Failed to parse model output", "files": []}

def apply_patch(repo_path: str, patch_data: dict) -> list[str]:
    """
    Applies the files generated by Gemini to the local workspace.
    """
    modified_files = []
    for file_info in patch_data.get("files", []):
        rel_path = file_info.get("path")
        content = file_info.get("content")
        if not rel_path or not content:
            continue

        full_path = os.path.join(repo_path, rel_path)
        os.makedirs(os.path.dirname(full_path), exist_ok=True)
        with open(full_path, "w", encoding="utf-8") as f:
            f.write(content)
        modified_files.append(rel_path)
        print(f"[Solver] Applied patch to: {rel_path}")

    return modified_files
